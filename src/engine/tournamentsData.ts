export function buildSupplementaryEuropeanClubs(): Club[] {
  return EXTRA_EURO_SEEDS.map((seed, cIdx) => {
    const scale = seed.rep >= 85 ? 1.25 : seed.rep >= 79 ? 1.05 : 0.88;
    const core: Player[] = seed.stars.map((st, pIdx) => {
      const p = makePlayer(
        `${seed.id}_p${pIdx}`,
        st[0],
        st[1],
        st[2],
        st[3],
        st[4],
        st[5],
        st[6],
        st[7],
        4000 + cIdx * 37 + pIdx * 11,
        scale
      );
      return { ...p, nationalTeamId: NAT_CODE_TO_TEAM_ID[st[3]] };
    });

    const fillerRoles: PlayerRole[] = ['GK', 'CB', 'LB', 'RB', 'CDM', 'CM', 'CAM', 'LW', 'RW', 'ST'];
    const fillers: Player[] = fillerRoles.map((role, fIdx) => {
      const fn = FIRST_NAMES[(cIdx * 3 + fIdx) % FIRST_NAMES.length];
      const ln = LAST_NAMES[(cIdx * 5 + fIdx) % LAST_NAMES.length];
      const ovr = Math.max(66, Math.min(79, seed.rep - 7 + ((fIdx * 2) % 4)));
      const p = makePlayer(
        `${seed.id}_b${fIdx}`,
        `${fn[0]}. ${ln}`,
        `${fn} ${ln}`,
        20 + ((cIdx + fIdx) % 9),
        seed.countryCode,
        role,
        ovr,
        Math.min(86, ovr + 5),
        40 + fIdx,
        5500 + cIdx * 29 + fIdx * 13,
        scale
      );
      return { ...p, nationalTeamId: NAT_CODE_TO_TEAM_ID[seed.countryCode] };
    });

    return {
      id: seed.id,
      leagueId: 'SUPER_LIG',
      fictionalName: seed.fictionalName,
      realName: seed.realName,
      fictionalShort: seed.fictionalShort,
      realShort: seed.realShort,
      city: seed.city,
      stadiumFictional: seed.stadiumFictional,
      stadiumReal: seed.stadiumReal,
      stadiumCapacity: seed.capacity,
      primaryColor: seed.primary,
      secondaryColor: seed.secondary,
      accentColor: seed.accent,
      kitPattern: seed.pattern,
      emblemType: seed.emblemType,
      crestShape: seed.crestShape,
      stars: seed.rep >= 85 ? 2 : 0,
      foundedYear: 1908 + ((cIdx * 7) % 60),
      realBadgeUrl: '',
      realKitUrl: '',
      transferBudget: seed.budget,
      wageBudgetWeekly: Math.round(seed.budget * 0.045),
      cashBalance: seed.budget * 1.9,
      reputation: seed.rep,
      boardExpectation: 'Avrupa Kupalarında Son 16 & Grup Liderliği',
      boardConfidence: 70,
      preferredFormation: seed.formation,
      players: [...core, ...fillers],
    };
  });
}

export interface GlobalEuropeanSelection {
  allClubs: Club[];
  uclIds: string[];
  uelIds: string[];
  ueclIds: string[];
}

export function assembleGlobalEuropeanCatalog(
  worldLeagues: Partial<Record<LeagueId, { clubs: Club[] }>>,
  primaryLeagueId: LeagueId,
  primaryClubs: Club[]
): GlobalEuropeanSelection {
  const clubMap = new Map<string, Club>();

  const register = (list: Club[]) => {
    for (const c of list) {
      if (!clubMap.has(c.id)) {
        clubMap.set(c.id, assignNationalTeamIdsToClub(c));
      }
    }
  };

  register(primaryClubs);
  const leagueOrder: LeagueId[] = [
    'PREMIER_LEAGUE',
    'LA_LIGA',
    'SERIE_A',
    'BUNDESLIGA',
    'SUPER_LIG',
    'EFL_CHAMPIONSHIP',
    'TR_1_LIG',
  ];
  for (const lid of leagueOrder) {
    if (lid === primaryLeagueId) continue;
    const fromWorld = worldLeagues[lid]?.clubs;
    register(fromWorld && fromWorld.length > 0 ? fromWorld : createClubsForLeague(lid));
  }
  register(buildSupplementaryEuropeanClubs());

  const byLeague = (lid: LeagueId) =>
    Array.from(clubMap.values())
      .filter((c) => c.leagueId === lid && !c.id.startsWith('eur_'))
      .sort((a, b) => b.reputation - a.reputation);

  const extraIds = EXTRA_EURO_SEEDS.map((s) => s.id);
  const pl = byLeague('PREMIER_LEAGUE');
  const ll = byLeague('LA_LIGA');
  const sa = byLeague('SERIE_A');
  const bl = byLeague('BUNDESLIGA');
  const sl = byLeague('SUPER_LIG');
  const chp = byLeague('EFL_CHAMPIONSHIP');

  const uclSet = new Set<string>();
  const addIds = (target: Set<string>, ids: string[], limit?: number) => {
    let added = 0;
    for (const id of ids) {
      if (limit !== undefined && added >= limit) break;
      if (clubMap.has(id) && !target.has(id)) {
        target.add(id);
        added++;
      }
    }
  };

  // UCL 36: Top 5 PL, Top 5 La Liga, Top 5 Serie A, Top 5 Bundesliga, Top 2 Süper Lig (GS/FB), Top 14 Extra Euro (PSG, Benfica, Porto, Sporting, PSV, Feyenoord, Ajax, Monaco, Marseille, Lille, Brugge, Celtic, Salzburg, Shakhtar)
  addIds(uclSet, pl.slice(0, 5).map((c) => c.id));
  addIds(uclSet, ll.slice(0, 5).map((c) => c.id));
  addIds(uclSet, sa.slice(0, 5).map((c) => c.id));
  addIds(uclSet, bl.slice(0, 5).map((c) => c.id));
  addIds(uclSet, sl.slice(0, 2).map((c) => c.id));
  addIds(uclSet, extraIds.slice(0, 14));

  const uelSet = new Set<string>();
  const pickFree = (list: Club[], count: number) =>
    list.filter((c) => !uclSet.has(c.id) && !uelSet.has(c.id)).slice(0, count).map((c) => c.id);

  // UEL 36: Next PL(5), LaLiga(5), SerieA(5), Bundesliga(5), SüperLig(4: BJK, TS, Başakşehir, Göztepe), plus remaining Extra Euro
  addIds(uelSet, pickFree(pl, 5));
  addIds(uelSet, pickFree(ll, 5));
  addIds(uelSet, pickFree(sa, 5));
  addIds(uelSet, pickFree(bl, 5));
  addIds(uelSet, pickFree(sl, 4));
  addIds(
    uelSet,
    extraIds.filter((id) => !uclSet.has(id) && !uelSet.has(id)),
    12
  );

  const ueclSet = new Set<string>();
  const pickFreeUecl = (list: Club[], count: number) =>
    list
      .filter((c) => !uclSet.has(c.id) && !uelSet.has(c.id) && !ueclSet.has(c.id))
      .slice(0, count)
      .map((c) => c.id);

  // UECL 36: Next PL(6), LaLiga(6), SerieA(6), Bundesliga(6), SüperLig(5), Championship/Euro rest
  addIds(ueclSet, pickFreeUecl(pl, 6));
  addIds(ueclSet, pickFreeUecl(ll, 6));
  addIds(ueclSet, pickFreeUecl(sa, 6));
  addIds(ueclSet, pickFreeUecl(bl, 6));
  addIds(ueclSet, pickFreeUecl(sl, 5));
  addIds(ueclSet, pickFreeUecl(chp, 7));

  // Pad to 36 in case any league was customized
  const allOrdered = Array.from(clubMap.values()).sort((a, b) => b.reputation - a.reputation);
  for (const c of allOrdered) {
    if (uclSet.size < 36 && !uclSet.has(c.id)) uclSet.add(c.id);
    else if (uelSet.size < 36 && !uclSet.has(c.id) && !uelSet.has(c.id)) uelSet.add(c.id);
    else if (ueclSet.size < 36 && !uclSet.has(c.id) && !uelSet.has(c.id) && !ueclSet.has(c.id)) {
      ueclSet.add(c.id);
    }
  }

  return {
    allClubs: Array.from(clubMap.values()),
    uclIds: Array.from(uclSet).slice(0, 36),
    uelIds: Array.from(uelSet).slice(0, 36),
    ueclIds: Array.from(ueclSet).slice(0, 36),
  };
}
