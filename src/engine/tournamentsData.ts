export function buildInitialNationalTeams(): NationalTeam[] {
  return NATION_SEEDS.map((seed, sIdx) => {
    const scale = seed.reputation >= 88 ? 1.2 : seed.reputation >= 80 ? 1.0 : 0.82;
    const corePlayers: Player[] = seed.stars.map((st, idx) => {
      const p = makePlayer(
        `${seed.id}_p${idx}`,
        st[0],
        st[1],
        st[2],
        seed.code,
        st[3],
        st[4],
        st[5],
        st[6],
        1000 + sIdx * 37 + idx * 11,
        scale
      );
      return { ...p, nationalTeamId: seed.id };
    });

    // Pad to 23-player international squad
    const backupOvrBase = Math.max(66, seed.reputation - 13);
    const benchPlayers: Player[] = BENCH_FILLER_ROLES.map((role, bIdx) => {
      const fn = FIRST_NAMES[(sIdx * 5 + bIdx) % FIRST_NAMES.length];
      const ln = LAST_NAMES[(sIdx * 3 + bIdx * 2) % LAST_NAMES.length];
      const ovr = Math.max(65, Math.min(82, backupOvrBase + ((bIdx * 3) % 5) - 2));
      const p = makePlayer(
        `${seed.id}_b${bIdx}`,
        `${fn[0]}. ${ln}`,
        `${fn} ${ln}`,
        21 + ((sIdx + bIdx) % 9),
        seed.code,
        role,
        ovr,
        Math.min(88, ovr + 4),
        12 + bIdx,
        2000 + sIdx * 41 + bIdx * 13,
        scale
      );
      return { ...p, nationalTeamId: seed.id };
    });

    return {
      id: seed.id,
      code: seed.code,
      fictionalName: seed.fictionalName,
      realName: seed.realName,
      fictionalShort: seed.fictionalShort,
      realShort: seed.realShort,
      tier: seed.tier,
      group: seed.group,
      primaryColor: seed.primary,
      secondaryColor: seed.secondary,
      accentColor: seed.accent,
      reputation: seed.reputation,
      stadiumFictional: seed.stadiumFictional,
      stadiumReal: seed.stadiumReal,
      stadiumCapacity: seed.capacity,
      preferredFormation: seed.formation,
      players: [...corePlayers, ...benchPlayers],
    };
  });
}

