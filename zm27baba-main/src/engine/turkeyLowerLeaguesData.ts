function buildGenericLowerSeed(
  id: string,
  fictionalName: string,
  realName: string,
  short: string,
  city: string,
  stadiumFictional: string,
  stadiumReal: string,
  capacity: number,
  primary: string,
  secondary: string,
  accent: string,
  budget: number,
  rep: number,
  seedOffset: number
): ClubSeed {
  const firsts = [
    'Ahmet', 'Mehmet', 'Emre', 'Can', 'Burak', 'Oğuzhan', 'Yusuf', 'Kerem', 'Furkan', 'Alperen',
    'Batuhan', 'Uğur', 'Mert', 'Kaan', 'Serkan', 'Hakan', 'Volkan', 'İbrahim', 'Onur', 'Tolga',
    'Berat', 'Arda', 'Eren', 'Semih', 'Salih', 'Taha', 'Doğukan', 'Görkem', 'Cem', 'Sefa',
  ];
  const lasts = [
    'Yılmaz', 'Kaya', 'Demir', 'Şahin', 'Çelik', 'Yıldız', 'Arslan', 'Öztürk', 'Aydın', 'Aksoy',
    'Kılıç', 'Aslan', 'Çakır', 'Koç', 'Kurt', 'Aktaş', 'Erdoğan', 'Karahan', 'Tekin', 'Güneş',
    'Doğan', 'Keskin', 'Ünal', 'Polat', 'Özcan', 'Tunç', 'Kaplan', 'Güler', 'Sönmez', 'Duman',
  ];
  const roles: Array<[PlayerRole, number, number]> = [
    ['GK', 27, 1], ['LB', 24, 3], ['CB', 28, 4], ['CB', 25, 5], ['RB', 26, 2],
    ['CDM', 27, 6], ['CM', 25, 8], ['CAM', 26, 10], ['LW', 24, 11], ['RW', 26, 7],
    ['ST', 28, 9], ['GK', 22, 34], ['CB', 23, 22], ['LB', 22, 23], ['RB', 23, 24],
    ['CM', 22, 14], ['ST', 23, 19], ['LW', 21, 17],
  ];

  const baseOvr = Math.max(59, Math.min(66, rep + 7));
  const roster: ClubSeed['roster'] = roles.map(([role, ageBase, shirt], i) => {
    const f = firsts[(seedOffset * 7 + i * 5) % firsts.length];
    const l = lasts[(seedOffset * 11 + i * 3) % lasts.length];
    const real = `${f} ${l}`;
    const fic = `${f[0]}. ${l.slice(0, 6)}`;
    const age = ageBase + ((seedOffset + i) % 5) - 2;
    const ovr = Math.max(58, Math.min(68, baseOvr + (i < 11 ? 2 : 0) - (i % 3)));
    const pot = Math.min(77, ovr + (age <= 23 ? 7 : 2));
    return [fic, real, age, 'TUR', role, ovr, pot, shirt];
  });

  return {
    id,
    fictionalName,
    realName,
    fictionalShort: `${short.slice(0, 2)}X`,
    realShort: short,
    city,
    stadiumFictional,
    stadiumReal,
    capacity,
    primary,
    secondary,
    accent,
    pattern: seedOffset % 2 === 0 ? 'STRIPES' : 'SOLID',
    emblemType: seedOffset % 3 === 0 ? 'FALCON' : seedOffset % 2 === 0 ? 'CASTLE' : 'SHIELD_GET',
    crestShape: seedOffset % 2 === 0 ? 'SHIELD' : 'CIRCLE',
    stars: 0,
    foundedYear: 1960 + (seedOffset % 45),
    budget,
    wageCap: Math.round(budget * 0.145),
    rep,
    expectation: rep >= 58 ? 'Play-Off Mücadelesi' : 'Ligde Kalıcılık & İstikrar',
    formation: seedOffset % 2 === 0 ? '4-2-3-1' : '4-4-2',
    roster,
  };
}

function buildClubsFromSeeds(
  seeds: ClubSeed[],
  leagueId: 'TR_1_LIG' | 'TR_2_LIG_BEYAZ' | 'TR_2_LIG_KIRMIZI',
  leagueScale: number,
  seedMult: number,
  makePlayerFn: (
    id: string,
    fictionalName: string,
    realName: string,
    age: number,
    nationality: string,
    role: PlayerRole,
    ovr: number,
    potential: number,
    shirtNumber: number,
    seed: number,
    leagueScale?: number
  ) => Player
): Club[] {
  return seeds.map((seed, cIdx) => {
    const players = seed.roster.map((p, pIdx) =>
      makePlayerFn(
        `${seed.id}_p${pIdx}`,
        p[0],
        p[1],
        p[2],
        p[3],
        p[4],
        p[5],
        p[6],
        p[7],
        seedMult + cIdx * 31 + pIdx * 9,
        leagueScale
      )
    );
    const totalWages = players.reduce((s, p) => s + p.weeklyWage, 0);
    const hardcoreWageCap = Math.max(seed.wageCap, Math.round((totalWages * 1.18) / 1000) * 1000);

    return {
      id: seed.id,
      leagueId,
      fictionalName: seed.fictionalName,
      realName: seed.realName,
      fictionalShort: seed.fictionalShort,
      realShort: seed.realShort,
      city: seed.city,
      stadiumFictional: seed.stadiumFictional,
      stadiumReal: seed.stadiumReal,
      stadiumCapacity: seed.capacity,
      primaryColor: seed.primary,
      secondaryColor: seed.secondary,
      accentColor: seed.accent,
      kitPattern: seed.pattern,
      emblemType: seed.emblemType,
      crestShape: seed.crestShape,
      stars: seed.stars,
      foundedYear: seed.foundedYear,
      realBadgeUrl: '',
      realKitUrl: '',
      transferBudget: seed.budget,
      wageBudgetWeekly: hardcoreWageCap,
      cashBalance: seed.budget * 1.9,
      reputation: seed.rep,
      boardExpectation: seed.expectation,
      boardConfidence: 68,
      preferredFormation: seed.formation,
      players,
    };
  });
}

