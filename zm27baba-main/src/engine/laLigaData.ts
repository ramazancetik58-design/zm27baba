export type MakePlayerFn = (
  id: string,
  fictionalName: string,
  realName: string,
  age: number,
  nationality: string,
  role: PlayerRole,
  ovr: number,
  potential: number,
  shirtNumber: number,
  seed: number,
  leagueScale?: number
) => Player;

export function buildLaLigaClubs(makePlayer: MakePlayerFn): Club[] {
  return LA_LIGA_SEEDS.map((seed, cIdx) => {
    const players = seed.roster.map((p, pIdx) =>
      makePlayer(
        `${seed.id}_p${pIdx}`,
        p[0],
        p[1],
        p[2],
        p[3],
        p[4],
        p[5],
        p[6],
        p[7],
        (cIdx + 40) * 31 + pIdx * 7 + 5,
        seed.id === 'sev' ? 0.45 : seed.rep >= 90 ? 1.45 : 1.05
      )
    );

    const totalWages = players.reduce((s, p) => s + p.weeklyWage, 0);
    // Sevilla is famously squeezed by La Liga LCPD cap (€388K/wk) — keep strict hardcore cap!
    const hardcoreWageCap =
      seed.id === 'sev'
        ? seed.wageCap
        : Math.max(seed.wageCap, Math.round((totalWages * 1.15) / 1000) * 1000);

    return {
      id: seed.id,
      leagueId: 'LA_LIGA',
      fictionalName: seed.fictionalName,
      realName: seed.realName,
      fictionalShort: seed.fictionalShort,
      realShort: seed.realShort,
      city: seed.city,
      stadiumFictional: seed.stadiumFictional,
      stadiumReal: seed.stadiumReal,
      stadiumCapacity: seed.capacity,
      primaryColor: seed.primary,
      secondaryColor: seed.secondary,
      accentColor: seed.accent,
      kitPattern: seed.pattern,
      emblemType: seed.emblemType,
      crestShape: seed.crestShape,
      stars: seed.stars,
      foundedYear: seed.foundedYear,
      realBadgeUrl: '',
      realKitUrl: '',
      transferBudget: seed.budget,
      wageBudgetWeekly: hardcoreWageCap,
      cashBalance: seed.budget * 1.85,
      reputation: seed.rep,
      boardExpectation: seed.expectation,
      boardConfidence: 68,
      preferredFormation: seed.formation,
      players,
    };
  });
}
